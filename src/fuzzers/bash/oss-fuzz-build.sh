# Read command line arguments
if [[ "$#" -ne 1 ]]; then
  cat >&2 <<EOF
Generates fuzzer runner scripts to be employed by Google OSS-Fuzz.
For details, see: http://logging.apache.org/log4cxx/fuzzing.html

Usage: $0 <outputDir>

  outputDir

    The output directory to dump runner scripts and their dependencies.
EOF
  exit 1
fi
outputDir=$(readlink -f "$1")

# Ensure output directory exists
mkdir -p "$outputDir"

# Switch to the project directory (by referencing from the script directory)
cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && cd ../../..

# Build a fuzzer with each encoding
declare -a encodings=("utf-8" "wchar_t")

for encoding in "${encodings[@]}"
do
  # Build the project
  mkdir -p build-"${encoding}" && cd $_
  cmake \
    -DBUILD_SHARED_LIBS=OFF \
    -DBUILD_TESTING=OFF \
    -DBUILD_EXAMPLES=OFF \
    -DBUILD_FUZZERS=ON \
    -DLOG4CXX_CHAR="${encoding}" \
    ..
  cmake --build . -j

  # Copy executables & resources
  find src/fuzzers/cpp -maxdepth 1 -executable -type f -exec cp -v {} "$outputDir/" \;
  cp ../src/fuzzers/resources/* "$outputDir/"
  cd .. && rm -r build-"${encoding}"
done

# PropertyConfiguratorFuzzer: seed property configurations from
# src/fuzzers/corpus/propertyconfigurator, packaged for both target
# encodings, together with a configuration dictionary.
zip -j "$outputDir/PropertyConfiguratorFuzzer-utf-8_seed_corpus.zip" src/fuzzers/corpus/propertyconfigurator/*
cp -f "$outputDir/PropertyConfiguratorFuzzer-utf-8_seed_corpus.zip" "$outputDir/PropertyConfiguratorFuzzer-wchar_t_seed_corpus.zip"
cp -f src/fuzzers/corpus/propertyconfigurator.dict "$outputDir/PropertyConfiguratorFuzzer-utf-8.dict"
cp -f src/fuzzers/corpus/propertyconfigurator.dict "$outputDir/PropertyConfiguratorFuzzer-wchar_t.dict"

# DOMConfiguratorFuzzer: seed XML configuration files from the test
# resources, packaged under the generic runner name, copied to the exact
# per-target names the runners use, and given a configuration dictionary
# for both encodings.
zip "$outputDir/DOMConfiguratorFuzzer_seed_corpus.zip" src/test/resources/input/xml/*.xml
cp -f "$outputDir/DOMConfiguratorFuzzer_seed_corpus.zip" "$outputDir/DOMConfiguratorFuzzer-utf-8_seed_corpus.zip"
cp -f "$outputDir/DOMConfiguratorFuzzer_seed_corpus.zip" "$outputDir/DOMConfiguratorFuzzer-wchar_t_seed_corpus.zip"
cp -f src/fuzzers/corpus/domconfigurator.dict "$outputDir/DOMConfiguratorFuzzer-utf-8.dict"
cp -f src/fuzzers/corpus/domconfigurator.dict "$outputDir/DOMConfiguratorFuzzer-wchar_t.dict"

# Layout and rolling-policy harnesses whose production corpus backups are
# missing (coverage jobs fail to unpack them) get seed corpora; the files
# are generated by src/fuzzers/corpus/gen_layout_seeds.py.
zip -j "$outputDir/HTMLLayoutFuzzer-utf-8_seed_corpus.zip" src/fuzzers/corpus/html-utf8/*
zip -j "$outputDir/XMLLayoutFuzzer-utf-8_seed_corpus.zip" src/fuzzers/corpus/xml-utf8/*
zip -j "$outputDir/XMLLayoutFuzzer-wchar_t_seed_corpus.zip" src/fuzzers/corpus/xml-wchar/*
zip -j "$outputDir/TimeBasedRollingPolicyFuzzer-utf-8_seed_corpus.zip" src/fuzzers/corpus/tbrp-utf8/*

